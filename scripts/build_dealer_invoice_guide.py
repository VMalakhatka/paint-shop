#!/usr/bin/env python3
"""Short invoice guide using existing sanitized customer-interface screenshots."""
from build_dealer_guides import Guide, HELP
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont


def main():
    pdfmetrics.registerFont(TTFont('Body', '/System/Library/Fonts/Supplemental/Arial.ttf'))
    pdfmetrics.registerFont(TTFont('Bold', '/System/Library/Fonts/Supplemental/Arial Bold.ttf'))
    pdfmetrics.registerFontFamily('Body', normal='Body', bold='Bold')
    g = Guide(5, 'payment-invoice', 'Як отримати рахунок на оплату', 2, '26.09.2026')
    g.page('Як отримати рахунок на оплату', 'Коротка інструкція для оптових клієнтів. Посилання у PDF можна натискати.')
    g.step(1, 'Увійдіть у кабінет', 'Відкрийте сайт під своїм логіном. У меню натисніть <b>«Документи ФОЛІО»</b> - це ваші документи в нашій базі.')
    g.shot('cabinet', 'Потрібний розділ виділено рамкою.', [(.54, .44, .16, .24)])
    g.link('Відкрити документи нашої бази', '/my-account/folio-documents/')
    g.step(2, 'Знайдіть потрібну покупку', 'Вкажіть період, у якому оформляли покупку. Залиште типи <b>«Рахунки»</b> та <b>«Видаткові накладні»</b>; «Платежі» для цього пошуку можна вимкнути. Натисніть <b>«Показати документи»</b>.')
    g.shot('documents-filter', 'Дати на фото - приклад. Виберіть свій період; особисті дані приховані.', [(.015, .54, .32, .18), (.335, .40, .315, .18), (.80, .49, .185, .24)])
    g.step(3, 'Відкрийте документ', 'У списку звірте <b>номер, дату, суму та склад</b>. Натисніть <b>«Переглянути»</b> у потрібному рядку та перевірте товари. Якщо кнопку не видно, прокрутіть таблицю вправо.')
    g.note('Можна і з видаткової накладної!', 'Рахунок на оплату завантажується як із рахунка, так і з видаткової накладної. Окремий початковий рахунок шукати необов’язково. Для платежів і повернень ця дія недоступна.')

    g.page('Завантажте файл і перевірте суму', 'Отримати рахунок - не означає оплатити його. Завантаження не змінює документ.')
    g.step(4, 'Натисніть «Рахунок XLSX»', 'У відкритому документі знайдіть блок <b>«Рахунок на оплату»</b>. Натисніть <b>«Рахунок XLSX»</b> і дочекайтеся завантаження. Відкрийте файл в Excel або іншій програмі для таблиць; за потреби роздрукуйте.')
    g.shot('document-export', 'Ліва кнопка - завантаження. Права - надсилання рахунка на email.', [(.006, .58, .156, .37), (.795, .58, .197, .37)])
    g.step(5, 'Або надішліть рахунок на email', 'Перевірте адресу отримувача; її можна змінити. Натисніть <b>«Надіслати на email»</b> один раз. Дочекайтеся результату, перевірте пошту та папку «Спам».')
    g.note('Важливо: у файлі ПОВНА сума документа', 'Попередні оплати автоматично не віднімаються. Якщо вже сплачували частину, перевірте залишок у <b>«Баланс із клієнтом»</b> або уточніть його в менеджера. Не сплачуйте повну суму повторно.', True)
    g.text('<b>Приклад:</b> документ на 5 000 грн, уже сплачено 2 000 грн. Файл усе одно міститиме 5 000 грн. Якщо інших коригувань немає, залишок становить 3 000 грн; перед оплатою звірте його з менеджером.', 11)
    g.link('Перевірити баланс', '/my-account/folio-balance/')
    g.note('Не знайшли документ або кнопку?', 'Розширте період і перевірте тип документа. Якщо рахунок не завантажується, відсутні реквізити або сума незрозуміла - повідомте менеджеру номер і дату документа. Пароль надсилати не потрібно.')
    g.link('Відкрити документи й отримати рахунок', '/my-account/folio-documents/')
    g.link('Повна інструкція: документи та рахунки', HELP + '#folio')
    g.save()


if __name__ == '__main__':
    main()
