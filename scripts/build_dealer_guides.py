#!/usr/bin/env python3
"""Build Ukrainian dealer guides from reviewed, irreversibly sanitized screenshots."""
from pathlib import Path
from reportlab.pdfgen import canvas
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.lib.colors import HexColor, white
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.platypus import Paragraph, Table, TableStyle
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'output/pdf'
IMG = ROOT / 'docs/images/dealer-guides'
BASE = 'https://kreul.com.ua'
HELP = BASE + '/my-account/yak-zamovyty/'
INK, TEAL, MUTED = map(HexColor, ['#203637', '#11635D', '#5D6E70'])
PALE, PAPER, AMBER = map(HexColor, ['#EAF4F0', '#FCFAF6', '#B7621B'])
W, H = A4
M, CW = 36, W - 72


class Guide:
    def __init__(self, number, slug, title, pages):
        self.number, self.pages, self.n = number, pages, 0
        self.path = OUT / f'kreul-dealer-{number:02}-{slug}-uk.pdf'
        self.c = canvas.Canvas(str(self.path), pagesize=A4, invariant=True)
        self.c.setTitle(title)
        self.c.setAuthor('Лавка Художника')
        self.c.setSubject('Покрокова інструкція дилеру. Знімки інтерфейсу з прихованими особистими даними.')

    def text(self, text, size=11.5, color=INK, bold=False, x=M, width=CW, gap=9):
        p = Paragraph(text, ParagraphStyle('body', fontName='Bold' if bold else 'Body',
                      fontSize=size, leading=size*1.35, textColor=color))
        _, h = p.wrap(width, H)
        assert self.y+h < 793, f'Page overflow {self.path.name}/{self.n}: {text[:70]}'
        p.drawOn(self.c,x,H-self.y-h)
        self.y += h+gap

    def page(self, title, sub):
        if self.n:
            self.c.showPage()
        self.n += 1
        c=self.c
        c.setFillColor(PAPER);c.rect(0,0,W,H,fill=1,stroke=0)
        c.setFillColor(TEAL);c.setFont('Bold',10)
        c.drawString(M,H-31,'ЛАВКА ХУДОЖНИКА  /  KREUL.COM.UA')
        c.setFont('Body',9);c.drawRightString(W-M,H-31,f'ДИЛЕРАМ  ·  ІНСТРУКЦІЯ {self.number:02}')
        c.setStrokeColor(HexColor('#D5E0DA'));c.line(M,H-45,W-M,H-45)
        c.line(M,43,W-M,43)
        c.setFont('Body',8);c.setFillColor(MUTED)
        c.drawString(M,28,'24.09.2026  ·  Приклади, не поточна пропозиція')
        c.drawRightString(W-M,28,f'{self.n} / {self.pages}')
        c.linkURL(HELP,(M,20,340,39),relative=0)
        self.y=62
        self.text(title,25,bold=True,gap=6)
        self.text(sub,10.5,MUTED,gap=17)

    def step(self, num, title, text):
        self.text(f'<font color="#11635D">{num:02}</font>  {title}',14,bold=True,gap=5)
        self.text(text,gap=13)

    def shot(self, name, caption, marks=(), width=CW):
        path=IMG/(name+'.png')
        iw,ih=Image.open(path).size
        height=width*ih/iw
        assert self.y+height+24 < 793, f'Image overflow {name}'
        self.c.drawImage(str(path),M,H-self.y-height,width=width,height=height)
        self.c.setStrokeColor(AMBER);self.c.setLineWidth(1.6)
        for x,y,w,h in marks:
            self.c.roundRect(M+x*width,H-self.y-(y+h)*height,w*width,h*height,3,fill=0,stroke=1)
        self.y+=height+5
        self.text(caption,8,MUTED,gap=13)

    def note(self, title, text, warning=False):
        p=Paragraph(f'<b>{title}</b><br/>{text}',ParagraphStyle('note',fontName='Body',fontSize=10.3,leading=14,textColor=INK))
        _,h=p.wrap(CW-26,H)
        assert self.y+h+25<793, f'Note overflow {title}'
        self.c.setFillColor(HexColor('#FFF0DD') if warning else PALE)
        self.c.roundRect(M,H-self.y-h-22,CW,h+22,8,fill=1,stroke=0)
        p.drawOn(self.c,M+13,H-self.y-h-11)
        self.y+=h+34

    def link(self,label,path):
        url=path if path.startswith('https:') else BASE+path
        self.text(f'<link href="{url}" color="#11635D"><b>{label} →</b></link>',11,gap=10)

    def table(self, rows, widths):
        style=ParagraphStyle('cell',fontName='Body',fontSize=10,leading=13,textColor=INK)
        data=[[Paragraph(str(s),style) for s in row] for row in rows]
        t=Table(data,colWidths=widths)
        t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),PALE),('VALIGN',(0,0),(-1,-1),'TOP'),
          ('GRID',(0,0),(-1,-1),.5,HexColor('#D5E0DA')),('LEFTPADDING',(0,0),(-1,-1),9),
          ('RIGHTPADDING',(0,0),(-1,-1),9),('TOPPADDING',(0,0),(-1,-1),8),('BOTTOMPADDING',(0,0),(-1,-1),8)]))
        _,h=t.wrap(CW,H)
        assert self.y+h<785
        t.drawOn(self.c,M,H-self.y-h);self.y+=h+15

    def save(self):
        assert self.n==self.pages
        self.c.save()
        print(self.path)


