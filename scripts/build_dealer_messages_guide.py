#!/usr/bin/env python3
"""Customer Messages/Telegram guide with vector teaching diagrams, no personal data."""
from build_dealer_guides import Guide, M, CW, H, TEAL, PALE, INK, MUTED, HELP
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.lib.colors import white, HexColor
from reportlab.platypus import Paragraph
from reportlab.lib.styles import ParagraphStyle


def diagram(g, boxes):
    """A compact left-to-right sequence, explicitly labelled as an illustration."""
    gap = 16
    width = (CW - gap * (len(boxes) - 1)) / len(boxes)
    height = 106
    assert g.y + height + 35 < 790
    for index, (title, body) in enumerate(boxes):
        x = M + index * (width + gap)
        g.c.setFillColor(PALE)
        g.c.roundRect(x, H - g.y - height, width, height, 9, fill=1, stroke=0)
        g.c.setFillColor(TEAL)
        g.c.circle(x + 19, H - g.y - 20, 10, fill=1, stroke=0)
        g.c.setFillColor(white)
        g.c.setFont('Bold', 10)
        g.c.drawCentredString(x + 19, H - g.y - 24, str(index + 1))
        p = Paragraph('<b>' + title + '</b><br/>' + body,
                      ParagraphStyle('diagram', fontName='Body', fontSize=10, leading=14, textColor=INK))
        _, h = p.wrap(width - 20, height)
        p.drawOn(g.c, x + 10, H - g.y - 40 - h)
        if index < len(boxes) - 1:
            g.c.setStrokeColor(TEAL)
            a = x + width + 2
            y = H - g.y - height / 2
            g.c.line(a, y, a + 12, y)
            g.c.line(a + 12, y, a + 8, y + 4)
            g.c.line(a + 12, y, a + 8, y - 4)
    g.y += height + 6
    g.text('Навчальна схема дій, не знімок екрана. Назви кнопок відповідають інтерфейсу.', 8, MUTED, gap=15)


