const fs = require('node:fs');
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fixture = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
if (new URL(fixture.shop).hostname !== 'paint.local') throw new Error('Local fixture only');
(async () => {
    const browser = await chromium.launch({headless:true, ...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {})});
    try {
        const guest = await browser.newPage();
        await guest.goto(fixture.simple);
        assert.equal(await guest.locator('.pcoe-catalog-toolbar').count(), 0, 'No guest toolbar');
        const guestResult = await guest.evaluate(async () => (await fetch('/wp-admin/admin-ajax.php', {method:'POST', body:new URLSearchParams({action:'pcoe_catalog_draft', operation:'create'})})).status);
        assert.notEqual(guestResult, 200, 'No unauthenticated route');
        await guest.close();
        for (const width of [390, 1280]) {
            const context = await browser.newContext({viewport:{width, height:900}});
            await context.addCookies([{name:fixture.cookie_name, value:fixture.cookie_value, domain:'paint.local', path:'/', httpOnly:true, secure:false}]);
            const page = await context.newPage();
            const errors = [];
            page.on('pageerror', error => { errors.push(error.message); console.error('Page error:', error.message); });
            await page.goto(fixture.category_url + '?in_stock=1');
            await page.waitForSelector('.pcoe-product-draft');
            assert.equal(await page.locator('.pcoe-catalog-toolbar').count(), 1, 'One mode selector');
            await page.locator('[data-pcoe-mode="purchase"]').click();
            await page.waitForSelector('body:not(.pcoe-draft-mode)');
            assert.equal(await page.locator('.pcoe-product-draft').count(), 0, 'Purchase controls restored');
            await page.locator('[data-pcoe-mode="draft"]').click();
            await page.waitForSelector('body.pcoe-draft-mode');
            await page.locator('.pcoe-new-draft summary').click();
            await page.locator('[data-pcoe-create] input').fill(`Browser planning ${width}`);
            const created = page.waitForEvent('framenavigated', frame => frame === page.mainFrame());
            await page.locator('[data-pcoe-create] button').click();
            await created;
            await page.waitForFunction(width => document.querySelector('[data-pcoe-draft] option:checked')?.textContent.includes(`Browser planning ${width}`), width);
            assert.notEqual(await page.locator('[data-pcoe-draft]').inputValue(), String(fixture.order_id), 'New draft selected');
            await page.locator('[data-pcoe-draft]').selectOption(String(fixture.order_id));
            await page.waitForFunction(id => document.querySelector('[data-pcoe-open]')?.href.includes('/' + id + '/'), fixture.order_id);
            const form = page.locator(`.pcoe-product-draft[data-product="${fixture.products[0]}"]`).first();
            await form.locator('input[name=quantity]').fill('1234');
            assert.equal(await form.locator('input[name=quantity]').getAttribute('max'), null);
            const response = page.waitForResponse(r => r.url().includes('admin-ajax.php') && r.request().postData()?.includes('operation=add'));
            await form.locator('button').click();
            assert.equal((await (await response).json()).success, true, 'Add out-of-stock from catalogue');
            await page.waitForFunction(() => !document.querySelector('[data-busy]'));
            await page.screenshot({path:`/tmp/catalog-draft-${width}.png`, fullPage:true});
            assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2), 'Catalogue fits viewport');
            await page.goto(fixture.variable);
            const variant = page.locator('.summary .pcoe-product-draft');
            await variant.locator('select').selectOption('Red');
            await variant.locator('[name=quantity]').fill('500');
            const variantResponse = page.waitForResponse(r => r.request().postData()?.includes('operation=add'));
            await variant.locator('button').click();
            assert.equal((await (await variantResponse).json()).success, true, 'Add out-of-stock variation');
            await page.waitForFunction(() => !document.querySelector('[data-busy]'));
            await page.screenshot({path:`/tmp/catalog-draft-product-${width}.png`, fullPage:true});
            assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2), 'Product fits viewport');
            await page.goto(fixture.order);
            await page.locator('.pcoe-draft-editor summary').click();
            assert.ok(await page.locator('[data-pcoe-update] input[type=number]').count() >= 3);
            await page.locator('[data-pcoe-update] input[type=number]').first().fill('900');
            const updated = page.waitForEvent('framenavigated', frame => frame === page.mainFrame());
            await page.locator('[data-pcoe-update] button').click();
            await updated;
            await page.waitForSelector('.pcoe-draft-editor');
            assert.equal(await page.locator('[data-pcoe-update] input[type=number]').first().inputValue(), '900', 'Edited quantity persisted');
            await page.screenshot({path:`/tmp/catalog-draft-editor-${width}.png`, fullPage:true});
            assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 2), 'Editor fits viewport');
            assert.equal(errors.length, 0, errors.join('\n'));
            console.log(`Catalogue draft real HTTP/UI ${width}px passed.`);
            await context.close();
        }
    } finally { await browser.close(); }
})().catch(error => {console.error(error); process.exitCode = 1;});
